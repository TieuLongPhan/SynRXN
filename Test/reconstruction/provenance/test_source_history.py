"""Original source pins and physical run snapshots detect source changes."""
import hashlib
import json
import subprocess
import sys

import pytest

from synrxn.reconstruction.families import suite
from synrxn.reconstruction.paths import REPO, legacy_path, source_path
from synrxn.reconstruction.provenance.source_history import load_tool


def test_source_moves_retain_original_bytes_and_explicit_entry_points():
    manifest = json.loads((REPO / 'synrxn/reconstruction/provenance/migration.json').read_text())
    assert len(manifest['entries']) == 41
    for entry in manifest['entries']:
        frozen = REPO / entry['frozen_path']
        assert frozen.stat().st_size == entry['original_bytes']
        assert hashlib.sha256(frozen.read_bytes()).hexdigest() == entry['original_sha256']
        assert source_path(entry['historical_path']) == frozen
        assert not (REPO / entry['historical_path']).exists()
        assert entry['historical_path_status'] == 'retired; root launcher removed'
        assert hashlib.sha256((REPO / entry['module_path']).read_bytes()).hexdigest() == entry['module_sha256']


def test_removed_tree_has_auditable_preserved_originals_and_assets():
    report = json.loads((REPO / 'archive/script_cleanup_manifest.json').read_text())
    assert not (REPO / 'script').exists()
    for record in report['entries']:
        if 'preserved_path' in record:
            payload = source_path(record['preserved_path']).read_bytes()
            assert hashlib.sha256(payload).hexdigest() == record['preserved_sha256']
            if 'redundant compatibility launcher' not in record['disposition']:
                assert record['preserved_sha256'] == record['historical_sha256']
        else:
            assert record['disposition'] == 'discarded generated bytecode cache'


@pytest.mark.parametrize('name', ['../run_ncs_pilot', '/tmp/tool', 'run_ncs_pilot.py', '', 'a/b'])
def test_legacy_tool_names_cannot_select_arbitrary_files(name):
    with pytest.raises(ValueError, match='tool name'):
        load_tool(name)


def test_legacy_loader_import_is_lazy_and_unguarded_workflows_are_archival_only():
    result = subprocess.run([sys.executable, '-S', '-c',
        'import sys; import synrxn.reconstruction.provenance.source_history; '
        'assert not any(k.startswith("synrxn.reconstruction.provenance.source_history._") for k in sys.modules)'],
        cwd=REPO, capture_output=True, text=True)
    assert result.returncode == 0, result.stderr
    with pytest.raises(ValueError, match='archived source only'):
        load_tool('build_ncs_latex')


def test_retired_source_snapshot_records_and_rechecks_the_preserved_file(tmp_path):
    repo, run = tmp_path / 'repo', tmp_path / 'run'
    relative = 'script/retired.py'
    archived = repo / 'archive/source-code' / relative
    archived.parent.mkdir(parents=True)
    archived.write_text('# original source\n')
    records = suite.snapshot_physical_files(run, [relative], repo)
    assert records[0]['path'] == relative
    assert records[0]['resolved_source_path'] == archived.relative_to(repo).as_posix()
    assert (run / 'snapshot' / relative).read_bytes() == archived.read_bytes()
    assert suite.physical_snapshot_changes(records, repo) == []
    archived.write_text('# changed source\n')
    assert suite.physical_snapshot_changes(records, repo) == [relative]


def test_historical_code_pins_resolve_original_bytes_with_an_explicit_alias():
    relative = 'kdd/coverage/rights.py'
    archived = legacy_path(relative)
    assert source_path(relative) == archived
    assert source_path(REPO / relative) == archived
    expected = hashlib.sha256(archived.read_bytes()).hexdigest()
    result = suite.audit_file({'path': relative, 'expected_sha256': expected}, REPO)
    assert result['status'] == 'verified'
    assert result['resolved_source_path'] == archived.relative_to(REPO).as_posix()
    assert not (REPO / relative).exists()  # Retired root launcher stays absent.


def test_physical_snapshot_preserves_public_shim_and_archived_kernel(tmp_path):
    repo, run = tmp_path / 'repo', tmp_path / 'run'
    relative = 'kdd/coverage/rights.py'
    shim = repo / relative
    archived = repo / 'archive/source-code' / relative
    shim.parent.mkdir(parents=True)
    archived.parent.mkdir(parents=True)
    shim.write_text('# physical compatibility entry point\n')
    archived.write_text('# byte-frozen historical kernel\n')
    records = suite.snapshot_physical_files(run, [relative], repo)
    by_path = {record['path']: record for record in records}
    archive_name = archived.relative_to(repo).as_posix()
    assert set(by_path) == {relative, archive_name}
    assert (run / 'snapshot' / relative).read_bytes() == shim.read_bytes()
    assert (run / 'snapshot' / archive_name).read_bytes() == archived.read_bytes()
    assert by_path[relative]['sha256'] == hashlib.sha256(shim.read_bytes()).hexdigest()
    assert by_path[relative]['historical_source_alias'] == {
        'logical_source_path': relative, 'resolved_source_path': archive_name,
        'sha256': hashlib.sha256(archived.read_bytes()).hexdigest()}
    assert suite.physical_snapshot_changes(records, repo) == []
    shim.write_text('# independently changed runtime entry point\n')
    assert suite.physical_snapshot_changes(records, repo) == [relative]
    # Original source pins still certify the unchanged historical kernel.
    pin = {'path': relative, 'expected_sha256': by_path[archive_name]['sha256']}
    assert suite.audit_file(pin, repo)['status'] == 'verified'
