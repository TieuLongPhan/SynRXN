"""Keep table entry point files aligned with the scientific task registry."""
from __future__ import annotations

import argparse
import json
from keyword import iskeyword
from pathlib import Path
import re

from ._selection import read_registry

ROOT = Path(__file__).resolve().parent
GENERATED = "# Generated by synrxn.reconstruction families sync-entries.\n"


def entry_sources(registry):
    """Return expected Python source for every registered family/task/table binding."""
    entries = {}
    families = {item['id'] for item in registry['families']}
    for task in registry['tasks']:
        family_id, task_id = task['family_id'], task['id']
        if family_id not in families or any(
            not name.isidentifier() or iskeyword(name) for name in (family_id, task_id)
        ):
            raise ValueError(f'Invalid family or task path for {family_id}/{task_id}')
        for binding in task['bindings']:
            table = (binding['namespace'], binding['key'])
            stem = re.sub(r'[^a-z0-9_]+', '_', table[1].rsplit('/', 1)[-1].lower()).strip('_')
            if stem.startswith('nmr_') and stem.endswith('_snapshots'):
                stem = stem.removesuffix('_snapshots') + '_spectra'
            if not stem.isidentifier() or iskeyword(stem):
                raise ValueError(f'Invalid table module name for {table}')
            path = Path(family_id, task_id, f'{stem}.py')
            if path in entries:
                raise ValueError(f'Duplicate table module path: {path}')
            entries[path] = (
                GENERATED
                + '"""Build or verify the source table for this task."""\n'
                + 'from synrxn.reconstruction.families._selection import table_main\n\n\n'
                + 'def main(argv=None):\n'
                + '    """Run this table binding."""\n'
                + f'    return table_main({family_id!r}, {task_id!r}, {table!r}, argv)\n\n\n'
                + 'if __name__ == "__main__":\n'
                + '    raise SystemExit(main())\n'
            )
    return entries


def sync_entries(registry, root=ROOT, *, check=False):
    """Synchronize generated launchers and preserve handwritten table recipes."""
    root = Path(root)
    expected = entry_sources(registry)
    actual = {path.relative_to(root): path.read_text(encoding='utf8')
              for path in root.glob('*/*/*.py')}
    changes = sorted(path for path, source in expected.items()
                     if path not in actual or (actual[path].startswith(GENERATED) and actual[path] != source))
    obsolete = sorted(path for path in actual.keys() - expected.keys() if actual[path].startswith(GENERATED))
    if not check:
        for path in changes:
            target = root / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(expected[path], encoding='utf8')
        for path in obsolete:
            target = root / path
            target.unlink()
            for parent in target.parents:
                if parent == root or any(parent.iterdir()):
                    break
                parent.rmdir()
    return {'entries': len(expected), 'updated': [p.as_posix() for p in changes],
            'obsolete': [p.as_posix() for p in obsolete]}


def main(argv=None):
    """Refresh or check the family/task/table entry points."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check for drift without writing files')
    args = parser.parse_args(argv)
    try:
        result = sync_entries(read_registry(), check=args.check)
    except ValueError as error:
        parser.error(str(error))
    print(json.dumps(result, indent=2))
    return int(args.check and bool(result['updated'] or result['obsolete']))
